<?php
/**
 * build-tokens.php — emit the design tokens as static SCSS (Phase 7).
 *
 * Phase 3 deferred static CSS emission to the Asset Pipeline (ADR-005).
 * This WP-free generator boots the real kernel and renders the token
 * repository's CSS (`:root` + `[data-phantom-theme]` blocks) into
 * `assets-src/scss/_tokens.scss`, which the Vite build compiles into the
 * shipped CSS. Re-run after changing `app/Tokens/config/*`.
 *
 * Usage: php bin/build-tokens.php
 * Exit code 0 = written; 1 = failure.
 *
 * @package Phantom
 * @since 0.7.0
 */

declare( strict_types=1 );

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', dirname( __DIR__ ) . '/' );
}

require dirname( __DIR__ ) . '/app/load.php';

use Phantom\Core\Boot\Kernel;
use Phantom\Core\Core\App;

Kernel::launch();

/** @var \Phantom\Core\Tokens\TokenRepository $repository */
$repository = App::instance()->make( 'tokens.repository' );
$css        = $repository->css( 'phantom' );

$target = dirname( __DIR__ ) . '/assets-src/scss/_tokens.scss';

// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- WP-free generator writing a build input.
$written = file_put_contents(
	$target,
	"// GENERATED by bin/build-tokens.php — do not edit by hand.\n" .
	"// Source of truth: app/Tokens/config/tokens.php + presets.php (Phase 3/7).\n" .
	"// Regenerate with: php bin/build-tokens.php\n\n" .
	$css
);

if ( false === $written ) {
	fwrite( STDERR, "Failed to write {$target}\n" ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI message.
	exit( 1 );
}

echo "Wrote {$target} (" . $written . " bytes)\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI message.
exit( 0 );
